def apply_op(op, do_apply):
    path = Path(op["file"])
    if not path.exists():
        raise SystemExit(f"FAIL: missing file: {path}")
    text = path.read_text(encoding="utf-8")
    old = op["old"]
    new = op["new"]
    old_count = text.count(old)
    new_count = text.count(new)

    if new_count == 1 and old_count == 0:
        print(f"SKIP: already applied: {op['name']}")
        return

    if old_count != 1 or new_count != 0:
        raise SystemExit(
            f"FAIL: anchor mismatch for {op['name']}: old={old_count}, new={new_count}"
        )

    print(f"READY: {op['name']}")
    if do_apply:
        path.write_text(
            text.replace(old, new, 1),
            encoding="utf-8",
            newline="\n",
        )
        print(f"APPLIED: {op['name']}")

def ensure_file(rel, content, do_apply):
    path = Path(rel)
    if path.exists():
        if path.read_text(encoding="utf-8") == content:
            print(f"SKIP: already present: {rel}")
            return
        raise SystemExit(f"FAIL: existing generated file differs: {rel}")
    print(f"READY: create {rel}")
    if do_apply:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"CREATED: {rel}")

